def _has(mod: str) -> bool:
    return importlib.util.find_spec(mod) is not None


def have_sandbox() -> bool:
    return bool(shutil.which("ffmpeg") and shutil.which("ffprobe") and _has("vapoursynth"))


def have_qtgmc_stack() -> bool:
    pdir = os.environ.get("QTGMC6UI_PLUGIN_DIR")
    return bool(pdir and Path(pdir).is_dir() and _has("vsdeinterlace"))


def pytest_runtest_setup(item: pytest.Item) -> None:
    if item.get_closest_marker("needs_sandbox") and not have_sandbox():
        pytest.skip("needs ffmpeg + vapoursynth (run inside tools/archrun)")
    if item.get_closest_marker("needs_qtgmc") and not have_qtgmc_stack():
        pytest.skip("needs QTGMC6UI_PLUGIN_DIR with the bundled plugins and vsjetpack")
    for m in item.iter_markers("needs_tool"):
        for tool in m.args:
            if not shutil.which(tool):
                pytest.skip(f"optional tool {tool} not installed")
    if item.get_closest_marker("gui"):
        os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")


